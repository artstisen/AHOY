using System;
using System.Runtime.InteropServices;
using System.Windows.Forms;

namespace AhoyBrowser
{
    /// <summary>
    /// Input Method Editor (Japanese, Chinese, Korean ...) helpers.
    /// While an IME is composing, the text box already contains the uncommitted characters,
    /// and every keystroke arrives as Keys.ProcessKey. Acting on that text (e.g. live search)
    /// interrupts the composition and closes the IME candidate window.
    /// </summary>
    internal static class ImeHelper
    {
        private const int GCS_COMPSTR = 0x0008;

        [DllImport("imm32.dll")]
        private static extern IntPtr ImmGetContext(IntPtr hWnd);

        [DllImport("imm32.dll")]
        private static extern bool ImmReleaseContext(IntPtr hWnd, IntPtr hIMC);

        [DllImport("imm32.dll", CharSet = CharSet.Unicode)]
        private static extern int ImmGetCompositionStringW(IntPtr hIMC, int dwIndex, IntPtr lpBuf, int dwBufLen);

        /// <summary>True while the IME for this control holds uncommitted text.</summary>
        internal static bool IsComposing(Control control)
        {
            if (control == null || !control.IsHandleCreated)
            {
                return false;
            }

            IntPtr context = ImmGetContext(control.Handle);
            if (context == IntPtr.Zero)
            {
                return false; // No IME attached
            }
            try
            {
                return ImmGetCompositionStringW(context, GCS_COMPSTR, IntPtr.Zero, 0) > 0;
            }
            finally
            {
                ImmReleaseContext(control.Handle, context);
            }
        }

        /// <summary>True for key events generated by an IME while composing.</summary>
        internal static bool IsImeKey(KeyEventArgs e)
        {
            return e.KeyCode == Keys.ProcessKey;
        }
    }
}
